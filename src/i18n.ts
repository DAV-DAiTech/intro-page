export const t = (
  key: TranslationKey,
  params?: Record<string, string | number>,
  dict: Translations = en
): string =>
  params
    ? dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''))
    : dict[key];
